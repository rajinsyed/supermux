describe("live local_command_output frames", () => {
  test("render as the same dim commandOutput line the replay path draws — one rendering for both", () => {
    const index = createIndex();
    let model = createModel();
    model = applyLine(model, index, diskUser("hello", "2026-08-18T19:21:15.611Z"), Date.now());
    model = applyLine(
      model,
      index,
      {
        type: "system",
        subtype: "local_command_output",
        content: "Set model to opus[1m] (claude-opus-5[1m])",
        uuid: uid("lco")
      } as ProtocolLine,
      Date.now()
    );
    const turn = model.turns[model.turns.length - 1];
    const output = turn.blocks.find((b) => b.kind === "commandOutput");
    expect(output).toBeDefined();
    expect(output!.kind === "commandOutput" && output!.text).toBe(
      "Set model to opus[1m] (claude-opus-5[1m])"
    );
    expect(turn.blocks.some((b) => b.kind === "notice")).toBe(false);
  });
});

